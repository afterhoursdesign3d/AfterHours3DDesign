/* ===========================================================
   BUILD SCRIPT - creates a real page for every design and every service item,
   refreshes the website address in the search/share tags, and writes
   sitemap.xml and robots.txt.

   Run it:      node tools/build.js
   On Cloudflare: Workers Builds > Settings > Build > Build command:  node tools/build.js
   (then it runs automatically every time you push to GitHub)

   Everything is created from js/designs-data.js, js/services-data.js and js/layout.js.
   The folders designs/ and services/ are rebuilt every time: don't edit files in them by hand.
   =========================================================== */
const fs = require("fs"), path = require("path"), vm = require("vm");
const root = path.join(__dirname, "..");
const read = f => fs.readFileSync(path.join(root, f), "utf8");
const write = (f, s) => { fs.mkdirSync(path.dirname(path.join(root, f)), { recursive: true }); fs.writeFileSync(path.join(root, f), s); };

// ---- load the site's own settings and data
const ctx = { location: { pathname: "/", protocol: "https:", hostname: "x", search: "" },
  document: { addEventListener() {}, querySelector() { return null; }, querySelectorAll() { return []; }, write() {}, body: { dataset: {} } },
  window: {}, console };
vm.createContext(ctx);
vm.runInContext(read("js/layout.js"), ctx);

vm.runInContext(read("js/designs-data.js"), ctx);
console.log("Designs data loaded");

vm.runInContext(read("js/services-data.js"), ctx);
console.log("Services data loaded");

const data = vm.runInContext(
  "({ DESIGNS, SERVICE_WORK })",
  ctx
);

const { SITE, PAGES, ITEM_FOLDERS } = ctx;
const base = SITE.url.replace(/\/$/, "");

// ---- helpers
const E = s => String(s == null ? "" : s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
const norm = i => typeof i === "string" ? { src: i, alt: "" } : i;
const abs = p => /^https?:/.test(p) ? p : base + "/" + p.replace(/^\//, "");
const cleanFile = f => SITE.cleanUrls ? f.replace(/\.html$/, "") : f;
const itemAddress = (type, id) => base + "/" + ITEM_FOLDERS[type] + "/" + encodeURIComponent(id) + (SITE.cleanUrls ? "" : ".html");
const shareImage = imgs => (imgs[0] && /\.(png|jpe?g|webp|gif)$/i.test(imgs[0].src)) ? abs(imgs[0].src) : base + "/assets/social-card.png";
const ARR = '<svg class="arr" viewBox="0 0 16 16" aria-hidden="true"><path d="M1.5 8h13M9 2.5 14.5 8 9 13.5"/></svg>';
const ARL = ARR.replace('class="arr"', 'class="arr arr-l"');
const img = (i, fallbackAlt) => `<img src="${E(i.src)}" alt="${E(i.alt || fallbackAlt)}" onerror="this.remove()">`;
const warn = m => console.warn("  WARNING: " + m);

// ---- shared bits copied from index.html so item pages always match the rest of the site
const index = read("index.html");
const fonts = (index.match(/<link rel="preconnect"[^>]*>\s*<link rel="preconnect"[^>]*>\s*<link href="https:\/\/fonts[^>]*>/) || [""])[0];
const icons = (index.match(/<!-- EDIT: favicon[\s\S]*?<link rel="stylesheet" href="css\/style\.css">/) || ['<link rel="stylesheet" href="css/style.css">'])[0];

function pageShell(o, main, scripts) {
  return `<!DOCTYPE html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<!-- CREATED BY tools/build.js FROM THE DATA FILES. Do not edit this file by hand. -->
<base href="../">
<title>${E(o.title)}</title>
<meta name="description" content="${E(o.desc)}">
<link rel="canonical" href="${E(o.url)}">
<meta property="og:type" content="website">
<meta property="og:site_name" content="After Hours Design">
<meta property="og:title" content="${E(o.title)}">
<meta property="og:description" content="${E(o.desc)}">
<meta property="og:url" content="${E(o.url)}">
<meta property="og:image" content="${E(o.image)}">
<meta property="og:image:alt" content="${E(o.imageAlt)}">
<meta name="twitter:card" content="summary_large_image">
${o.ld ? '<script type="application/ld+json">' + JSON.stringify(o.ld) + "</script>\n" : ""}${fonts}
${icons}</head>
<body data-header="hide-on-scroll">
<a class="skip" href="#main">Skip to content</a>
<script src="js/layout.js"></script><script>writeHeader();</script>
<main id="main">
${main}
</main>
<script>writeFooter();</script>
${scripts}<script src="js/main.js"></script>
</body></html>
`;
}

// ---- design pages
function designMain(d) {
  const im = (d.images || []).map(norm), ks = d.status === "kickstarter";
  const link = ks ? d.kickstarterUrl : d.buyUrl;
  if (!link) warn(`design "${d.id}" has no ${ks ? "kickstarterUrl" : "buyUrl"}, so its button is left out`);
  const thumbs = im.length > 1 ? im.map((i, k) => `<button type="button" aria-label="Image ${k + 1}"${k === 0 ? ' aria-current="true"' : ""}>${img(i, d.name)}</button>`).join("") : "";
  const specs = (d.specs && d.specs.length) ? `<ul class="specs">${d.specs.map(s => `<li>${E(s)}</li>`).join("")}</ul>` : "";
  return `<div class="container page-head"><a class="back" href="${E(PAGES.designs.file)}">${ARL}Back to ${E(PAGES.designs.title)}</a></div>
<div class="container"><div class="design">
<div><div class="ph r45 main-img" id="main-img">${im[0] ? img(im[0], d.name) : ""}</div><div class="thumbs" id="thumbs">${thumbs}</div></div>
<div><h1>${E(d.name)}</h1><h3>${ks ? "In the works" : E(d.price)}</h3><p>${E(d.description)}</p>${specs}${link ? `<a class="btn" href="${E(link)}">${ks ? "View on Kickstarter" : "Buy now"}</a>` : ""}</div>
</div></div>
<div class="lightbox" id="lb" hidden><button class="lb-close" aria-label="Close">&times;</button><button class="lb-prev" aria-label="Previous">&lsaquo;</button><img alt=""><button class="lb-next" aria-label="Next">&rsaquo;</button></div>`;
}

// ---- service item pages
function serviceMain(w) {
  const sp = PAGES[w.service], im = (w.images || []).map(norm), main = im[0], gal = im.slice(1);
  return `<section class="container svc-hero"><div class="svc-text"><a class="back" href="${E(sp.file)}">${ARL}Back to ${E(sp.title)}</a>
<div class="svc-body"><h1>${E(w.name)}</h1><p>${E(w.description)}</p><a class="btn" href="${E(PAGES.contact.file)}">Get a quote</a></div></div>
<div class="ph r45">${main ? img(main, w.name) : ""}</div></section>` +
    (gal.length ? `\n<section class="container gallery-sec${w.galleryText ? "" : " no-text"}">${w.galleryText ? `<p>${E(w.galleryText)}</p>` : ""}<div class="gallery">${gal.map(g => `<div class="ph r43">${img(g, w.name)}</div>`).join("")}</div></section>` : "");
}

const brand = { "@type": "Organization", name: "After Hours Design", url: base + "/" };
function priceNumber(p) { const m = String(p || "").replace(/,/g, "").match(/[\d.]+/); return m ? parseFloat(m[0]) : 0; }

console.log("Building pages...");
["designs", "services"].forEach(d => fs.rmSync(path.join(root, d), { recursive: true, force: true }));
let made = 0;
data.DESIGNS.forEach(d => {
  if (!/^[a-z0-9-]+$/.test(d.id)) warn(`design id "${d.id}" should be lowercase letters, numbers and hyphens only`);
  const im = (d.images || []).map(norm);
  const ld = (d.status === "available" && priceNumber(d.price) > 0) ? { "@context": "https://schema.org", "@type": "Product", name: d.name, description: d.shortDescription,
    image: im.map(i => abs(i.src)), brand, offers: { "@type": "Offer", price: priceNumber(d.price), priceCurrency: "GBP", availability: "https://schema.org/InStock", url: d.buyUrl || itemAddress("design", d.id) } } : null;
  write(`${ITEM_FOLDERS.design}/${d.id}.html`, pageShell({ title: `${d.name} | After Hours Design`, desc: d.shortDescription, url: itemAddress("design", d.id),
    image: shareImage(im), imageAlt: im[0] && im[0].alt || d.name, ld }, designMain(d), '<script src="js/gallery.js"></script>'));
  made++;
});
data.SERVICE_WORK.forEach(w => {
  if (!PAGES[w.service]) { warn(`item "${w.id}" has an unknown service "${w.service}", skipped`); return; }
  if (!/^[a-z0-9-]+$/.test(w.id)) warn(`item id "${w.id}" should be lowercase letters, numbers and hyphens only`);
  const im = (w.images || []).map(norm);
  const ld = { "@context": "https://schema.org", "@type": "Service", name: w.name, description: w.shortDescription, provider: brand, areaServed: SITE.place.areaServed };
  write(`${ITEM_FOLDERS.service}/${w.id}.html`, pageShell({ title: `${w.name} | After Hours Design`, desc: w.shortDescription, url: itemAddress("service", w.id),
    image: shareImage(im), imageAlt: im[0] && im[0].alt || w.name, ld }, serviceMain(w), ""));
  made++;
});
console.log(`  ${made} design and service pages created`);

// ---- refresh the website address in each page's search/share tags, and the home page's business details
fs.readdirSync(root).filter(f => f.endsWith(".html")).forEach(f => {
  let s = read(f);
  const start = s.indexOf("<!-- SEO:"), end = s.indexOf("<title>");
  if (start < 0 || end < start) return;
  const m = s.slice(start, end).match(/<meta property="og:image" content="(https?:\/\/[^\/"]+)/);
  let block = s.slice(start, end);
  if (m && m[1] !== base) block = block.split(m[1]).join(base);
  if (f === "index.html") {
    const ld = { "@context": "https://schema.org", "@type": "ProfessionalService", name: "After Hours Design", url: base + "/", logo: base + "/assets/favicon-192.png",
      image: base + "/assets/social-card.png", sameAs: [SITE.tiktok, SITE.instagram],
      address: { "@type": "PostalAddress", addressLocality: SITE.place.city, addressRegion: SITE.place.region, addressCountry: SITE.place.country }, areaServed: SITE.place.areaServed };
    if (!/yourdomain/.test(SITE.email)) ld.email = SITE.email;
    block = block.replace(/<script type="application\/ld\+json">[\s\S]*?<\/script>/, '<script type="application/ld+json">' + JSON.stringify(ld) + "</script>");
  }
  const out = s.slice(0, start) + block + s.slice(end);
  if (out !== s) write(f, out);
});

// ---- sitemap.xml and robots.txt
const EXCLUDE = ["privacy", "terms", "cookies"];   // pages left out of the sitemap. Remove a key to include it.
const urls = Object.keys(PAGES).filter(k => !EXCLUDE.includes(k)).map(k => k === "home" ? base + "/" : base + "/" + cleanFile(PAGES[k].file));
data.DESIGNS.forEach(d => urls.push(itemAddress("design", d.id)));
data.SERVICE_WORK.filter(w => PAGES[w.service]).forEach(w => urls.push(itemAddress("service", w.id)));
write("sitemap.xml", '<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n' +
  urls.map(u => "  <url><loc>" + u.replace(/&/g, "&amp;") + "</loc></url>").join("\n") + "\n</urlset>\n");
write("robots.txt", "User-agent: *\nAllow: /\n\nSitemap: " + base + "/sitemap.xml\n");
console.log(`  sitemap.xml (${urls.length} addresses) and robots.txt written for ${base}`);
